const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const read = relativePath => fs.readFileSync(path.join(root, relativePath), 'utf8')

const form = read('src/pages/volunteer/register.vue')
assert.match(form, /姓名\s*<text class="register__required">\*<\/text>/, 'registration form must collect a required real name')
assert.match(form, /学号\s*<text class="register__required">\*<\/text>/, 'registration form must collect a required student number')
assert.match(form, /性别\s*<text class="register__required">\*<\/text>/, 'registration form must collect a required gender')
assert.match(form, /邮箱/, 'registration form must collect an email address')
assert.match(form, /电话或邮箱至少填写一项/, 'registration form must explain the alternative contact requirement')
assert.match(form, /目标高中（选填）/, 'target high school must be optional in the registration form')
assert.match(form, /studentNo: form\.studentNo/, 'registration request must submit the student number')
assert.match(form, /gender: form\.gender/, 'registration request must submit the gender')
assert.match(form, /email:\s*email/, 'registration request must submit the normalized email')
assert.doesNotMatch(form, /if \(!form\.targetHighSchoolId\)/, 'registration must not block submission without a target high school')

const dto = read('backend/src/main/java/com/demo/miniprogram/dto/VolunteerApplyDTO.java')
assert.match(dto, /private String studentNo;/, 'backend request DTO must accept student number')
assert.match(dto, /private String gender;/, 'backend request DTO must accept gender')
assert.match(dto, /private String email;/, 'backend request DTO must accept email')
assert.doesNotMatch(dto, /@NotBlank\(message = "手机号不能为空"\)/, 'phone must not be individually required')
assert.doesNotMatch(dto, /@NotNull\(message = "目标高中不能为空"\)/, 'target high school must not be individually required')

const volunteer = read('backend/src/main/java/com/demo/miniprogram/entity/Volunteer.java')
assert.match(volunteer, /private String studentNo;/, 'volunteer entity must persist student number')
assert.match(volunteer, /private String gender;/, 'volunteer entity must persist gender')
assert.match(volunteer, /private String email;/, 'volunteer entity must persist email')

const service = read('backend/src/main/java/com/demo/miniprogram/service/VolunteerService.java')
assert.match(service, /电话或邮箱至少填写一项/, 'backend must enforce at least one contact method')
assert.match(service, /dto\.getTargetHighSchoolId\(\) != null/, 'backend must only create a high-school relation when supplied')
assert.match(service, /volunteer\.setStudentNo\(dto\.getStudentNo\(\)\.trim\(\)\)/, 'backend must save student number')
assert.match(service, /volunteer\.setGender\(dto\.getGender\(\)\.trim\(\)\)/, 'backend must save gender')
assert.match(service, /volunteer\.setEmail\(/, 'backend must save email')

const migration = read('backend/src/main/resources/db/volunteer_registration_fields.sql')
assert.match(migration, /student_no/, 'migration must add student number')
assert.match(migration, /gender/, 'migration must add gender')
assert.match(migration, /email/, 'migration must add email')
assert.match(migration, /MODIFY COLUMN phone/, 'migration must allow phone to be empty')
assert.doesNotMatch(migration, /DROP TABLE|TRUNCATE TABLE/i, 'migration must not destroy existing registration data')

console.log('Volunteer registration fields contract passed')
